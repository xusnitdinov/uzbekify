#!/usr/bin/env node
/**
 * Mine research/informal-corpus/ for real chat patterns (CORE MISSION voice
 * targets). Outputs research/informal-corpus/MINING.md and appends nothing to
 * code — the findings feed references/informal-chat.md and the aitell rules.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, "..", "..");
const DIR = path.join(REPO, "research", "informal-corpus");

const PATTERNS: { name: string; re: RegExp; examples?: number }[] = [
  { name: "particles -chi/-da/-ku/-yu/-mi (glued)", re: /\b\w+(?:chi|ku|yu|mi)\b/gi, examples: 6 },
  { name: "axir / endi / mayli / xoʻp / baribir", re: /\b(?:axir|endi|mayli|xoʻp|xop|baribir)\b/gi, examples: 6 },
  { name: "spoken forms: nma / qale / bovotti / kere / boladi / yoq", re: /\b(?:nma|qale|qaley|bovotti|kere|boladi|bola\b|yoq|yoʻqmi|qanaqa|qanday qilib)\b/gi, examples: 8 },
  { name: "dropped subject (verb-first short messages)", re: /^\s*(?:qildim|keldim|boraman|yozaman|olaman|toʻladim|yubordim|koʻrdim|bilaman|tushunmadim|ishlamadi|boʻlmadi|chiqmadi)\b/mi, examples: 4 },
  { name: "RU/EN code-switch tokens", re: /\b(?:udalit|zakaz|skidka|donat|crack|apk|reklama|limit|payme|pila|interneti|kk|bn|prosto|norm)\b/gi, examples: 8 },
  { name: "laughter: xaxa / ))) / axa", re: /(?:xaxa+|axa+|\)\)+)/gi, examples: 4 },
  { name: "emoji", re: /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/gu, examples: 8 },
  { name: "greetings/sign-offs", re: /\b(?:salom|assalomu alaykum|rahmat|tashakkur|rahmat aka|opa|aka|keyin koʻrishguncha|xayr)\b/gi, examples: 6 },
  { name: "glued spelling: bn / kk / qilib qoʻy-elisions", re: /\b\w*\s?(?:bn|kk|qoʻyla|bola qol)\b/gi, examples: 6 },
];

const APOS_VARIANTS: [string, RegExp][] = [
  ["oʻ (U+02BB)", /o\u02BB/g],
  ["o' (ASCII)", /o'/g],
  ["o‘ (U+2018)", /o\u2018/g],
  ["o` (grave)", /o`/g],
  ["ó (acute)", /ó/g],
  ["ö (umlaut)", /ö/g],
];

function main(): void {
  const files = fs.readdirSync(DIR).filter((f) => f.endsWith(".txt"));
  const corpus = new Map<string, string>();
  for (const f of files) corpus.set(f, fs.readFileSync(path.join(DIR, f), "utf8"));

  const all = [...corpus.values()].join("\n");
  const out: string[] = [];
  out.push("# Informal corpus mining (generated by src/scripts/mine-informal.ts)");
  out.push("");
  out.push("Sources: see MANIFEST.md. CORE MISSION: these are voice targets, the way real");
  out.push("people write; robotic AI versions are built against them in references/informal-chat.md.");
  out.push("");

  for (const p of PATTERNS) {
    const matches = all.match(p.re) ?? [];
    const uniq = [...new Set(matches.map((m) => m.trim()))];
    out.push(`## ${p.name}`);
    out.push("");
    out.push(`- hits: ${matches.length}, unique: ${uniq.length}`);
    if (p.examples && uniq.length) {
      const sample = uniq.slice(0, p.examples).map((s) => `\`${s}\``).join(", ");
      out.push(`- examples: ${sample}`);
    }
    out.push("");
  }

  out.push("## Apostrophe variant mixing in casual writing");
  out.push("");
  out.push("| Variant | Count |");
  out.push("|---|---|");
  for (const [name, re] of APOS_VARIANTS) {
    out.push(`| ${name} | ${(all.match(re) ?? []).length} |`);
  }
  out.push("");

  // sentence length of informal vs formal
  const tg = [...corpus.entries()].filter(([f]) => f.startsWith("tg-")).map(([, t]) => t).join("\n");
  const msgs = tg.split(/\n\n---\n\n|\n/).map((s) => s.trim()).filter((s) => s.length > 5 && !s.startsWith("#"));
  const lens = msgs.map((m) => m.split(/\s+/).length);
  out.push("## Message lengths (Telegram posts, informal-ish)");
  out.push("");
  out.push(`- messages: ${msgs.length}, mean words: ${(lens.reduce((a, b) => a + b, 0) / (lens.length || 1)).toFixed(1)}, median: ${[...lens].sort((a, b) => a - b)[Math.floor(lens.length / 2)]}`);
  out.push("");

  fs.writeFileSync(path.join(DIR, "MINING.md"), out.join("\n") + "\n", "utf8");
  console.log(out.filter((l) => l.startsWith("##") || l.includes("hits:")).join("\n"));
}

main();
